#!/bin/zsh
# COS Morning Briefing — runs the daily routine from CLAUDE.md unattended.
# Register with launchd (macOS) or cron (Linux) to fire each morning.
#
# SAFETY: --allowedTools intentionally EXCLUDES all email/message tools, so the
# unattended run can read your systems and create calendar blocks / update
# tasks, but can NEVER send anything on its own. Keep it that way.

COS_DIR="$HOME/PersonalChiefOfStaff"          # <-- your clone location
CLAUDE_BIN="$(command -v claude)"              # or the absolute path to claude
DATE="$(date +%Y-%m-%d)"
LOG_DIR="$COS_DIR/memory/conversations"
LOG_FILE="$LOG_DIR/$DATE.md"

mkdir -p "$LOG_DIR"
cd "$COS_DIR" || exit 1

PROMPT="It is the start of the day ($DATE). Run the Daily Routine defined in CLAUDE.md:
1. Read memory/context.txt and the task list.
2. Pull today's events from the calendar to find open blocks and avoid conflicts.
3. Pick the ONE thing that matters today, then choose max 3 'Today' tasks across the focus zones.
4. Auto-block calendar time for protected zones and any task flagged Auto-block.
5. Run any due autonomous agents; prepare drafts for anything that needs my approval (do NOT send).
6. Update memory/context.txt open loops.
7. Output a short, scannable morning briefing: today's plan, what you did autonomously, what needs my decision, and what you anticipate coming up.
Your printed output IS my morning briefing."

# Allowlist: local files + your calendar/task connectors. No email = cannot auto-send.
"$CLAUDE_BIN" -p "$PROMPT" \
  --allowedTools "Read Write Edit Bash [YOUR_CALENDAR_MCP] [YOUR_TASKS_MCP]" \
  > "$LOG_FILE" 2>&1

echo "" >> "$LOG_FILE"
echo "_Generated by morning_briefing.sh at $(date '+%H:%M %Z')_" >> "$LOG_FILE"
